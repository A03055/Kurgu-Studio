/* IndexedDB: medya dosyaları ve proje burada saklanır, hiçbir yere yüklenmez */
const DB = {
  db: null,
  open() {
    return new Promise((res, rej) => {
      if (!window.indexedDB) return rej(new Error('IndexedDB yok'));
      const r = indexedDB.open('kurgu-studio', 1);
      r.onupgradeneeded = () => {
        const d = r.result;
        if (!d.objectStoreNames.contains('media')) d.createObjectStore('media', { keyPath: 'id' });
        if (!d.objectStoreNames.contains('kv')) d.createObjectStore('kv');
      };
      r.onsuccess = () => { this.db = r.result; res(); };
      r.onerror = () => rej(r.error);
    });
  },
  _req(store, mode, fn) {
    return new Promise((res, rej) => {
      if (!this.db) return res(undefined);
      const tx = this.db.transaction(store, mode);
      const r = fn(tx.objectStore(store));
      tx.oncomplete = () => res(r && r.result);
      tx.onerror = () => rej(tx.error);
      tx.onabort = () => rej(tx.error);
    });
  },
  put(store, val, key) { return this._req(store, 'readwrite', s => s.put(val, key)); },
  get(store, key) { return this._req(store, 'readonly', s => s.get(key)); },
  getAll(store) { return this._req(store, 'readonly', s => s.getAll()); },
  del(store, key) { return this._req(store, 'readwrite', s => s.delete(key)); },
};
